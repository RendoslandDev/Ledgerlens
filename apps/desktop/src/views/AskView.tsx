import type { Answer, Report } from "@ledgerlens/bindings";
import { ArrowUp, CornerDownLeft, ShieldCheck } from "lucide-react";
import { type FormEvent } from "react";
import { money, monthLabel } from "../format";

export interface AskEntry {
  question: string;
  answer?: Answer;
  error?: string;
}

const suggestions = [
  "How much did we spend this month?",
  "Spend by vendor this year",
  "Which documents need review?",
];

export function AskView({
  question,
  setQuestion,
  entries,
  runAsk,
  asking,
  report,
}: {
  question: string;
  setQuestion: (question: string) => void;
  entries: AskEntry[];
  runAsk: (event: FormEvent<HTMLFormElement>) => void;
  asking: boolean;
  report: Report | null;
}) {
  const reviewed = report ? report.counts.extracted + report.counts.approved : 0;
  return (
    <section className="ask-layout">
      <div className="ask-main">
        <div className="ask-log">
          {entries.length === 0 ? (
            <div className="ask-empty">
              <h2>Query your records</h2>
              <p>
                Answers come from SQL over reviewed records. Ask about spend by period, vendor,
                category, or currency. Nothing leaves this device.
              </p>
              <div className="suggestions">
                {suggestions.map((suggestion) => (
                  <button key={suggestion} onClick={() => setQuestion(suggestion)}>
                    <CornerDownLeft size={13} aria-hidden="true" />
                    {suggestion}
                  </button>
                ))}
              </div>
            </div>
          ) : (
            entries.map((entry, index) => (
              <article className="ask-entry" key={index}>
                <div className="ask-question">
                  <span className="prompt-glyph mono">›</span>
                  {entry.question}
                </div>
                <div className="ask-answer">
                  {entry.error && <p className="error-text">{entry.error}</p>}
                  {!entry.answer && !entry.error && <p className="dim">Working…</p>}
                  {entry.answer && <AnswerBlock answer={entry.answer} />}
                </div>
              </article>
            ))
          )}
        </div>
        <form className="composer" onSubmit={runAsk}>
          <textarea
            value={question}
            onChange={(event) => setQuestion(event.target.value)}
            onKeyDown={(event) => {
              if (event.key === "Enter" && !event.shiftKey) {
                event.preventDefault();
                event.currentTarget.form?.requestSubmit();
              }
            }}
            maxLength={500}
            placeholder="Ask about spend, vendors, categories, or documents in review…"
            rows={2}
            aria-label="Ask a question"
          />
          <div className="composer-bar">
            <span>
              <ShieldCheck size={13} aria-hidden="true" /> Local · structured records only
            </span>
            <button
              className="button button-primary icon-only"
              type="submit"
              disabled={!question.trim() || asking}
              aria-label="Ask"
            >
              <ArrowUp size={15} />
            </button>
          </div>
        </form>
      </div>

      <aside className="ask-side">
        <div className="section-label">
          <span>Dataset</span>
        </div>
        <dl className="kv">
          <div>
            <dt>Reviewed records</dt>
            <dd className="mono">{reviewed}</dd>
          </div>
          <div>
            <dt>Waiting for review</dt>
            <dd className="mono">{report?.counts.needsReview ?? 0}</dd>
          </div>
          <div>
            <dt>Top category</dt>
            <dd>{report?.byCategory.find((row) => row.label)?.label ?? "—"}</dd>
          </div>
          <div>
            <dt>Currencies</dt>
            <dd className="mono">
              {report?.byCurrency.map((row) => row.currency).join(", ") || "—"}
            </dd>
          </div>
        </dl>
        <p className="side-note">
          Totals are calculated from records, not generated by a language model. Records still
          in review are left out until you check them.
        </p>
      </aside>
    </section>
  );
}

function AnswerBlock({ answer }: { answer: Answer }) {
  const grouped = answer.rows.length > 1 || answer.rows.some((row) => row.label !== null);
  return (
    <>
      <p>{answer.answer}</p>
      {grouped && (
        <div className="mini-table answer-table">
          {answer.rows.map((row, index) => (
            <div className="mini-row" key={index}>
              <span>
                {row.label === null
                  ? row.currency
                  : /^\d{4}-\d{2}$/.test(row.label)
                    ? monthLabel(row.label)
                    : row.label}
              </span>
              <span className="dim mono">{row.count}</span>
              <span className="mono num">{money(row.totalMinor, row.currency)}</span>
            </div>
          ))}
        </div>
      )}
      {answer.pendingReview > 0 && (
        <p className="dim small-note">
          {answer.pendingReview} matching record{answer.pendingReview === 1 ? " is" : "s are"}{" "}
          still in review and not counted.
        </p>
      )}
      {answer.sql && <pre className="query-plan mono">{answer.sql}</pre>}
    </>
  );
}
