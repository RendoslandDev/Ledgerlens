//! Tauri command layer: thin, typed wrappers over `ll_app::App`. Each command validates its
//! arguments, runs off the main thread, and returns `{ code, message }` errors.
//!
//! TypeScript bindings for the typed commands are generated from this crate with `tauri-specta`
//! into `packages/bindings/src/bindings.ts` (ADR 0003). After changing a command or a boundary
//! type, run `npm --prefix apps/desktop run bindings`.

mod commands;
mod folder_dialog;

use ll_app::background::Background;
use std::sync::{Arc, Mutex};
use tauri::{Manager, Runtime};
use tauri_specta::{collect_commands, Builder};

pub struct AppState {
    pub app: Arc<Mutex<ll_app::App>>,
    /// Reads queued documents and scans the watched folder (`ll_app::background`).
    pub background: Background,
}

impl AppState {
    fn start(service: ll_app::App) -> std::io::Result<Self> {
        let app = Arc::new(Mutex::new(service));
        let background = Background::start(Arc::clone(&app))?;
        Ok(Self { app, background })
    }
}

/// Raw-body commands carry file bytes, which `specta` cannot describe; they are dispatched by
/// Tauri directly and typed by hand in `packages/bindings/src/raw.ts`.
const RAW_COMMANDS: [&str; 2] = ["import_document", "document_file"];

/// Every command whose arguments and result are typed by `specta`, for one concrete runtime
/// (`collect_commands!` cannot take a generic one): `tauri::Wry` in the app, the mock runtime in
/// the IPC tests.
macro_rules! typed_commands {
    ($runtime:path) => {
        collect_commands![
            commands::list_documents::<$runtime>,
            commands::get_document::<$runtime>,
            commands::update_field::<$runtime>,
            commands::approve_document::<$runtime>,
            commands::reprocess_document::<$runtime>,
            commands::delete_document::<$runtime>,
            commands::open_document_file::<$runtime>,
            commands::ask::<$runtime>,
            commands::report::<$runtime>,
            commands::export_records::<$runtime>,
            commands::export_plan::<$runtime>,
            commands::approve_ready::<$runtime>,
            commands::vendors::<$runtime>,
            commands::search::<$runtime>,
            commands::get_settings::<$runtime>,
            commands::update_settings::<$runtime>,
            commands::system_info::<$runtime>,
            commands::categories,
            commands::activity,
            commands::cancel_import::<$runtime>,
            commands::cancel_pending_imports::<$runtime>,
            commands::watch_status::<$runtime>,
            commands::choose_watch_folder::<$runtime>,
            commands::set_watch_enabled::<$runtime>,
            commands::forget_watch_folder::<$runtime>,
            commands::scan_watch_folder,
        ]
    };
}

fn specta_base<R: Runtime>() -> Builder<R> {
    // One TypeScript shape per type: boundary types travel in a single direction.
    Builder::<R>::new()
        .disable_serde_phases()
        // Returned by the raw `import_document` command, so not reachable from a typed signature.
        .typ::<ll_app::ImportOutcome>()
}

fn specta_builder() -> Builder<tauri::Wry> {
    specta_base().commands(typed_commands!(tauri::Wry))
}

#[cfg(test)]
/// 64-bit integers are not exported implicitly; each such field in `ll-app` opts in to `number`
/// with `specta_typescript::Number`, next to the bound that keeps it exact
/// (`ll_app::MAX_SAFE_MINOR`).
fn typescript() -> specta_typescript::Typescript {
    specta_typescript::Typescript::default()
        .header("// Generated by tauri-specta from apps/desktop/src-tauri. Do not edit by hand.")
}

fn raw_handler<R: Runtime>() -> impl Fn(tauri::ipc::Invoke<R>) -> bool + Send + Sync + 'static {
    tauri::generate_handler![commands::import_document, commands::document_file]
}

/// Wires state and both command handlers onto a builder; shared by the app and the IPC tests.
fn configure<R: Runtime>(
    builder: tauri::Builder<R>,
    typed: impl Fn(tauri::ipc::Invoke<R>) -> bool + Send + Sync + 'static,
) -> tauri::Builder<R> {
    let raw = raw_handler::<R>();
    builder
        .setup(|app| {
            let mut data_dir = app.path().app_data_dir()?;
            // Debug builds can point at a scratch workspace; release builds always use app data.
            if cfg!(debug_assertions) {
                if let Some(dir) = std::env::var_os("LEDGERLENS_DATA_DIR") {
                    data_dir = dir.into();
                }
            }
            let service = ll_app::App::open(&data_dir)?;
            app.manage(AppState::start(service)?);
            Ok(())
        })
        .invoke_handler(move |invoke| {
            if RAW_COMMANDS.contains(&invoke.message.command()) {
                raw(invoke)
            } else {
                typed(invoke)
            }
        })
}

/// The app's config, assets, and permission manifest (expanded once per crate).
fn context<R: Runtime>() -> tauri::Context<R> {
    tauri::generate_context!()
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    configure(tauri::Builder::default(), specta_builder().invoke_handler())
        .run(context())
        .expect("failed to run Ledgerlens desktop application");
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    /// Fails when the committed bindings no longer match the Rust commands and types.
    #[test]
    fn bindings_are_current() {
        let committed = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../../../packages/bindings/src/bindings.ts");
        let fresh = std::env::temp_dir().join(format!("ll-bindings-{}.ts", std::process::id()));
        specta_builder()
            .export(typescript(), &fresh)
            .expect("bindings export");
        let generated = std::fs::read_to_string(&fresh).expect("generated bindings");
        let _ = std::fs::remove_file(&fresh);
        if std::env::var_os("LEDGERLENS_WRITE_BINDINGS").is_some() {
            std::fs::write(&committed, &generated).expect("write bindings");
            return;
        }
        let current = std::fs::read_to_string(&committed).unwrap_or_default();
        assert!(
            current == generated,
            "packages/bindings/src/bindings.ts is stale: run `npm --prefix apps/desktop run bindings`"
        );
    }

    /// Drives the real command layer through Tauri's IPC with the mock runtime: typed commands
    /// go through `tauri-specta`, raw-byte commands through Tauri, all against a real `ll_app`.
    #[test]
    fn commands_dispatch_through_ipc() {
        use serde_json::{json, Value};
        use tauri::{
            ipc::{CallbackFn, InvokeBody},
            test::{get_ipc_response, mock_builder, MockRuntime, INVOKE_KEY},
            webview::InvokeRequest,
        };

        let data_dir = std::env::temp_dir().join(format!("ll-ipc-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&data_dir);
        let typed = specta_base::<MockRuntime>()
            .commands(typed_commands!(tauri::test::MockRuntime))
            .invoke_handler();
        let app = configure(mock_builder(), typed)
            // The app's real config and permission manifest, so the ACL is exercised too.
            .build(context())
            .expect("mock app");
        // The mock runtime does not run `setup` on build; register the same state it would.
        app.manage(AppState::start(ll_app::App::open(&data_dir).expect("service")).expect("worker"));
        let webview = tauri::WebviewWindowBuilder::new(&app, "main", Default::default())
            .build()
            .expect("mock webview");
        // The app's own origin in a dev build (`devUrl`); anything else counts as remote.
        let app_origin = "http://localhost:1420";
        let request_from = |origin: &str, cmd: &str, body: InvokeBody, headers: tauri::http::HeaderMap| InvokeRequest {
            cmd: cmd.into(),
            callback: CallbackFn(0),
            error: CallbackFn(1),
            url: origin.parse().unwrap(),
            body,
            headers,
            invoke_key: INVOKE_KEY.to_string(),
        };
        let request = |cmd: &str, body: InvokeBody, headers: tauri::http::HeaderMap| {
            request_from(app_origin, cmd, body, headers)
        };
        let call = |cmd: &str, args: Value| {
            get_ipc_response(&webview, request(cmd, InvokeBody::Json(args), Default::default()))
                .map(|body| body.deserialize::<Value>().unwrap())
        };

        assert_eq!(call("list_documents", json!({})).unwrap(), json!([]));

        // A page from any other origin cannot reach the app's commands.
        let remote = get_ipc_response(
            &webview,
            request_from("https://example.com", "list_documents", InvokeBody::Json(json!({})), Default::default()),
        );
        assert!(remote.is_err(), "remote origins must be refused");

        let pdf = include_bytes!("../../../../crates/ll-app/tests/fixtures/invoice-cups.pdf").to_vec();
        let mut headers = tauri::http::HeaderMap::new();
        headers.insert("x-file-name", "Kumasi%20invoice.pdf".parse().unwrap());
        let imported = get_ipc_response(&webview, request("import_document", InvokeBody::Raw(pdf.clone()), headers))
            .map(|body| body.deserialize::<Value>().unwrap())
            .expect("raw import");
        let id = imported["document"]["id"].as_str().unwrap().to_string();
        assert_eq!(imported["document"]["fileName"], "Kumasi invoice.pdf");
        // Import returns once the file is stored; the background worker reads it.
        assert_eq!(imported["document"]["status"], "queued");

        let deadline = std::time::Instant::now() + std::time::Duration::from_secs(30);
        let detail = loop {
            let detail = call("get_document", json!({ "id": id })).unwrap();
            if detail["summary"]["status"] == "extracted" {
                break detail;
            }
            assert!(std::time::Instant::now() < deadline, "the worker did not read the import");
            std::thread::sleep(std::time::Duration::from_millis(50));
        };
        assert_eq!(detail["summary"]["vendor"], "Kumasi Cloud Services Ltd");
        assert_eq!(detail["summary"]["totalMinor"], 172_500);
        let activity = call("activity", json!({})).unwrap();
        assert!(activity["revision"].as_u64().unwrap() > 0);
        assert_eq!(activity["watching"], false);

        // Watching is off until a folder is chosen in the system dialog; no command takes a path.
        let watch = call("watch_status", json!({})).unwrap();
        assert_eq!((watch["folder"].clone(), watch["enabled"].clone()), (Value::Null, json!(false)));
        assert_eq!(call("set_watch_enabled", json!({ "enabled": true })).unwrap_err()["code"], "invalid");

        // Cancelling: a second, never-read import is removed; a read one cannot be cancelled.
        let mut headers = tauri::http::HeaderMap::new();
        headers.insert("x-file-name", "blank.png".parse().unwrap());
        let png = include_bytes!("../../../../crates/ll-app/tests/fixtures/blank.png").to_vec();
        let queued = get_ipc_response(&webview, request("import_document", InvokeBody::Raw(png), headers))
            .map(|body| body.deserialize::<Value>().unwrap())
            .expect("second import");
        let queued_id = queued["document"]["id"].as_str().unwrap().to_string();
        // The worker may already be reading it; cancelling covers both states.
        if call("cancel_import", json!({ "id": queued_id })).is_ok() {
            assert!(call("get_document", json!({ "id": queued_id })).is_err());
        }
        assert_eq!(call("cancel_import", json!({ "id": id })).unwrap_err()["code"], "invalid");

        let bytes = get_ipc_response(&webview, request("document_file", InvokeBody::Json(json!({ "id": id })), Default::default()))
            .expect("raw file");
        match bytes {
            tauri::ipc::InvokeResponseBody::Raw(raw) => assert_eq!(raw, pdf),
            other => panic!("expected raw bytes, got {other:?}"),
        }

        let rejected = call("update_field", json!({ "id": id, "edit": { "field": "total", "value": "12abc" } }))
            .unwrap_err();
        assert_eq!(rejected["code"], "invalid");
        assert!(call("get_document", json!({ "id": "not-an-id" })).is_err());

        drop(app);
        let _ = std::fs::remove_dir_all(&data_dir);
    }

    #[test]
    fn raw_commands_stay_out_of_the_generated_bindings() {
        let fresh = std::env::temp_dir().join(format!("ll-raw-{}.ts", std::process::id()));
        specta_builder().export(typescript(), &fresh).expect("bindings export");
        let generated = std::fs::read_to_string(&fresh).expect("generated bindings");
        let _ = std::fs::remove_file(&fresh);
        for name in RAW_COMMANDS {
            assert!(!generated.contains(&format!("\"{name}\"")), "{name} is typed by hand");
        }
    }
}
